import type { IJsonSchemaUnit, IValidation } from '@typia/interface';

/**
 * The contract a site's `pageSchemas` / `dataSchemas` entries are written in.
 *
 * A site's content schema is dynamic from this package's point of view — it is
 * declared in the host's own source and only reaches the CMS at runtime — so the
 * CMS cannot generate anything for it. The host does, with Typia, where the type
 * lives:
 *
 * ```ts
 * import typia from 'typia';
 *
 * interface BlogFields {
 *   // A JSDoc comment here becomes the field's help text in the editor.
 *   excerpt?: string;
 * }
 *
 * export const articleFields = defineHostSchema<BlogFields>({
 *   validate: typia.createValidate<BlogFields>(),
 *   metadata: typia.json.schema<BlogFields>(),
 * });
 * ```
 *
 * Both members are compiler output for the same `T`: `validate` is what the
 * build validates stored entries with (`@conloca/astro-cms`'s loader), and
 * `metadata` is the JSON Schema the editor renders its form from. Nothing here
 * re-describes the shape by hand, and the `T` parameter ties the two together at
 * compile time.
 *
 * `typia.plain.createValidatePrune<T>()` is the Zod-`z.object()` equivalent for
 * `validate`: on success it also drops undeclared nested keys. Plain
 * `typia.createValidate<T>()` keeps them.
 */
export interface HostSchema<T extends object = object> {
  /** A generated Typia validator for `T` (`typia.createValidate<T>()` or `typia.plain.createValidatePrune<T>()`). */
  readonly validate: (input: unknown) => IValidation<T>;
  /** Generated JSON Schema metadata for `T` (`typia.json.schema<T>()`). */
  readonly metadata: IJsonSchemaUnit<'3.1', T>;
}

/** The value type a {@link HostSchema} validates — the `z.infer` of this contract. */
export type HostSchemaType<S> = S extends HostSchema<infer T> ? T : never;

/**
 * Typed identity for a {@link HostSchema}. Refuses at declaration time what the
 * editor and the loader could not use: a validator that is not a function, or
 * metadata whose root is not an object type (content entries are records).
 */
export function defineHostSchema<T extends object>(schema: HostSchema<T>): HostSchema<T> {
  if (typeof schema.validate !== 'function') {
    throw new Error('defineHostSchema: `validate` must be a generated Typia validator (typia.createValidate<T>()).');
  }
  if (schema.metadata?.version !== '3.1' || rootObjectOf(schema.metadata) === null) {
    throw new Error(
      'defineHostSchema: `metadata` must be `typia.json.schema<T>()` (JSON Schema 3.1) for an object type T.',
    );
  }
  return schema;
}

/** Generated JSON Schema metadata, whatever type it was generated for. */
export type HostSchemaMetadata = IJsonSchemaUnit.IV3_1<unknown>;
type JsonSchema = HostSchemaMetadata['schema'];
type JsonObjectSchema = Extract<JsonSchema, { type: 'object' }>;

/** `$ref`s generated by `typia.json.schema` all point into the unit's own components. */
const SCHEMA_REF_PREFIX = '#/components/schemas/';

/**
 * Follow a generated `$ref` to its component. Returns the schema unchanged when
 * it is not a reference, and `null` for a reference the unit does not carry.
 */
export function resolveHostJsonSchema(
  metadata: HostSchemaMetadata,
  node: JsonSchema,
): Exclude<JsonSchema, { $ref: string }> | null {
  let current: JsonSchema | undefined = node;
  // A named type can only alias another named type a bounded number of times.
  for (let hops = 0; current && '$ref' in current; hops++) {
    if (hops > 16 || !current.$ref.startsWith(SCHEMA_REF_PREFIX)) return null;
    current = metadata.components.schemas?.[current.$ref.slice(SCHEMA_REF_PREFIX.length)];
  }
  return current ?? null;
}

/** The object schema at the root of generated metadata, or `null` when the root is not an object. */
export function rootObjectOf(metadata: HostSchemaMetadata): JsonObjectSchema | null {
  const root = resolveHostJsonSchema(metadata, metadata.schema);
  return root && 'type' in root && root.type === 'object' ? root : null;
}

/** The top-level field names a host schema declares, in declaration order. */
export function hostSchemaFieldNames(schema: HostSchema): string[] {
  return Object.keys(rootObjectOf(schema.metadata)?.properties ?? {});
}
